#!/usr/bin/env python3
"""Does the knowledge profile change how an agent explains things? Three conditions per question:

  A  none   no information about the learner
  B  bio    one-line bio only ("MBA, business undergrad, ...")
  C  tree   the full rendered profile block (what the SessionStart hook injects)

Answers are generated by Claude (headless `claude -p`, the actual product model) with the condition
text appended to the system prompt, or by OpenAI with --generator openai. A separate judge model
(OpenAI) reads each answer holding the persona's profile and reports:

  unexplained   concepts the answer relies on without defining, that the persona does not know
  new           concepts the answer introduces with a definition (the rules budget is <= 2)
  followups     "what is X?" questions a simulated persona would ask next
  words         answer length (the tree should not just make answers longer)

Usage:
  ~/.venvs/ukm/bin/python eval/run_eval.py                # Claude generation, resumes from results.json
  ~/.venvs/ukm/bin/python eval/run_eval.py --fresh        # ignore cached answers/judgments
  ~/.venvs/ukm/bin/python eval/run_eval.py --generator openai
  ~/.venvs/ukm/bin/python eval/run_eval.py --only phys-top,math-deriv --conditions A,C
Writes eval/results.json (raw) and eval/results.md (tables).
"""
from __future__ import annotations

import argparse
import json
import os
import statistics
import subprocess
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import lib  # noqa: E402
from render_context import RULES, render  # noqa: E402

EVAL = ROOT / "eval"
RESULTS_JSON = EVAL / "results.json"
RESULTS_MD = EVAL / "results.md"
CONDITIONS = {"A": "none", "B": "bio", "C": "tree"}

JUDGE_SYSTEM = """You evaluate whether an explanation was pitched correctly for one specific learner.
You are given the learner's knowledge profile, their question, and an answer written for them.

Work through the answer and list every concept it relies on (technical terms, ideas, mechanisms).
For each, say whether the answer defines or explains it inline (defined_inline), and classify the
learner's status from the profile:
  knows            listed under KNOWS WELL
  has_seen         listed under HAS SEEN BUT MAY NOT RECALL or PROBABLY FAMILIAR
  does_not_know    listed under DOES NOT KNOW, or a concept inside such an area
  unlisted_likely  not listed, but this learner almost certainly knows it (everyday knowledge,
                   or implied by their background)
  unlisted_unlikely not listed, and this learner probably does not know it

Then:
  unexplained_dependencies: concepts with defined_inline=false whose status is does_not_know or
      unlisted_unlikely. These are the places the learner gets lost.
  new_concepts_introduced: concepts with defined_inline=true whose status is not "knows".
  learner_followup_message: write the learner's most likely next message, in their voice, after
      reading this answer. If they would ask "what is X?" style questions, include them.
  followup_questions: the concept names the learner asks about in that message (empty if none).

Be strict and literal: an analogy is not a definition of the technical term it stands in for, but
an answer that never uses the technical term at all has no dependency on it.
Return JSON with keys: concepts, unexplained_dependencies, new_concepts_introduced,
learner_followup_message, followup_questions. `concepts` is a list of
{name, defined_inline, status}."""


def profile_block_without_rules(profile: dict) -> str:
    block = render(profile)
    return block.split("\n\nHow to explain things to this user:")[0].replace("<knowledge-profile>\n", "")


def condition_text(cond: str, profile: dict) -> str | None:
    if cond == "A":
        return None
    if cond == "B":
        return (f"About the user you are talking to: {profile['bio']} "
                "Pitch your explanation accordingly.")
    return render(profile)


# ---------------------------------------------------------------- generation

def gen_claude(question: str, system_extra: str | None, model: str | None, timeout: int = 300) -> str:
    env = {k: v for k, v in os.environ.items() if k not in ("CLAUDECODE", "CLAUDE_CODE_ENTRYPOINT")}
    env["UKM_DISABLED"] = "1"
    env["KNOWLEDGE_HOME"] = tempfile.mkdtemp(prefix="ukm-eval-")
    cmd = ["claude", "-p", question, "--output-format", "text"]
    if system_extra:
        cmd += ["--append-system-prompt", system_extra]
    if model:
        cmd += ["--model", model]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, env=env,
                       stdin=subprocess.DEVNULL, cwd=str(Path.home()))
    out = r.stdout.strip()
    if r.returncode != 0 or not out:
        raise RuntimeError(f"claude -p failed ({r.returncode}): {r.stderr.strip()[:300]}")
    return out


def gen_openai(question: str, system_extra: str | None, timeout: int = 120) -> str:
    c = lib.openai_client(timeout=timeout)
    msgs = []
    if system_extra:
        msgs.append({"role": "system", "content": system_extra})
    msgs.append({"role": "user", "content": question})
    r = c.chat.completions.create(model=lib.MODEL_GEN, messages=msgs, max_completion_tokens=2500)
    return (r.choices[0].message.content or "").strip()


# ---------------------------------------------------------------- judging

def judge(profile_block: str, question: str, answer: str) -> dict:
    """Reasoning models spend the completion budget on hidden reasoning first; give them room and
    retry at lower effort if the content came back empty."""
    c = lib.openai_client(timeout=240)
    payload = json.dumps({"learner_profile": profile_block, "question": question, "answer": answer})
    last = None
    for effort, budget in (("low", 16000), ("minimal", 8000)):
        r = c.chat.completions.create(
            model=lib.MODEL_JUDGE, response_format={"type": "json_object"}, reasoning_effort=effort,
            messages=[{"role": "system", "content": JUDGE_SYSTEM}, {"role": "user", "content": payload}],
            max_completion_tokens=budget)
        content = r.choices[0].message.content or ""
        last = (r.choices[0].finish_reason, r.usage.completion_tokens)
        try:
            j = json.loads(content)
        except json.JSONDecodeError:
            j = {}
        if j.get("concepts") is not None:
            return j
    raise RuntimeError(f"judge returned no usable JSON (finish={last[0]}, completion_tokens={last[1]})")


def metrics(answer: str, j: dict) -> dict:
    return {
        "unexplained": len(j.get("unexplained_dependencies", [])),
        "new": len(j.get("new_concepts_introduced", [])),
        "followups": len(j.get("followup_questions", [])),
        "words": len(answer.split()),
    }


# ---------------------------------------------------------------- report

def mean(xs):
    return statistics.mean(xs) if xs else float("nan")


def write_report(results: dict, questions: list[dict], meta: dict) -> str:
    conds = [c for c in CONDITIONS if any(f"{q['id']}|{c}" in results for q in questions)]
    lines = ["# Eval: does the knowledge profile change the explanation?", "",
             f"Generator: {meta['generator']}. Judge: {meta['judge']}. Persona: {meta['persona']}. "
             f"{len(questions)} questions x {len(conds)} conditions. Run {meta['run_at']}.", "",
             "Conditions: **A** no learner info, **B** one-line bio, **C** full profile block (what the "
             "SessionStart hook injects). Lower is better for unexplained and followups; `new` should be "
             "<= 2 under C's rules; words shows whether C just makes answers longer.", "",
             "## Means per condition", "",
             "| condition | unexplained deps | followup questions | new concepts (defined) | words |",
             "|---|---|---|---|---|"]
    for c in conds:
        rows = [results[f"{q['id']}|{c}"]["metrics"] for q in questions if f"{q['id']}|{c}" in results]
        lines.append(f"| {c} ({CONDITIONS[c]}) | {mean([r['unexplained'] for r in rows]):.2f} | "
                     f"{mean([r['followups'] for r in rows]):.2f} | {mean([r['new'] for r in rows]):.2f} | "
                     f"{mean([r['words'] for r in rows]):.0f} |")
    # split: areas the persona does not know vs controls
    lines += ["", "### Same, only the six questions in areas the persona does not know", "",
              "| condition | unexplained deps | followup questions | new concepts | words |", "|---|---|---|---|---|"]
    hard = [q for q in questions if "unknown" in q["area"]]
    for c in conds:
        rows = [results[f"{q['id']}|{c}"]["metrics"] for q in hard if f"{q['id']}|{c}" in results]
        if rows:
            lines.append(f"| {c} ({CONDITIONS[c]}) | {mean([r['unexplained'] for r in rows]):.2f} | "
                         f"{mean([r['followups'] for r in rows]):.2f} | {mean([r['new'] for r in rows]):.2f} | "
                         f"{mean([r['words'] for r in rows]):.0f} |")
    lines += ["", "## Per question (unexplained deps / followups)", "",
              "| question | area | " + " | ".join(f"{c}" for c in conds) + " |",
              "|---|---|" + "---|" * len(conds)]
    for q in questions:
        cells = []
        for c in conds:
            r = results.get(f"{q['id']}|{c}")
            cells.append(f"{r['metrics']['unexplained']} / {r['metrics']['followups']}" if r else "-")
        lines.append(f"| {q['id']} | {q['area']} | " + " | ".join(cells) + " |")
    lines += ["", "## What the learner got lost on (unexplained dependencies, by answer)", ""]
    for q in questions:
        lines.append(f"**{q['id']}** ({q['area']}): {q['q']}")
        for c in conds:
            r = results.get(f"{q['id']}|{c}")
            if not r:
                continue
            deps = r["judgment"].get("unexplained_dependencies", [])
            fu = r["judgment"].get("followup_questions", [])
            lines.append(f"- {c}: unexplained = {deps or 'none'}; learner asks about = {fu or 'nothing'}")
        lines.append("")
    lines += ["## Method notes", "",
              "- The judge holds the persona's profile (the lists, not the rules) and classifies every concept "
              "the answer relies on. `unexplained` counts concepts used without an inline definition that the "
              "persona does not know. `followups` counts 'what is X?' questions in a simulated next message.",
              "- Generator and judge are different model families to reduce self-preference.",
              "- n = 10 questions; treat differences under ~1 point as noise. Raw judgments are in results.json.",
              ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--generator", choices=["claude", "openai"], default="claude")
    ap.add_argument("--claude-model", default=None, help="model for claude -p (default: your configured model)")
    ap.add_argument("--profile", default=str(ROOT / "data" / "profile.persona-mba.json"))
    ap.add_argument("--only", default=None, help="comma-separated question ids")
    ap.add_argument("--conditions", default="A,B,C")
    ap.add_argument("--fresh", action="store_true")
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()

    profile = json.loads(Path(args.profile).read_text())
    spec = json.loads((EVAL / "questions.json").read_text())
    questions = spec["questions"]
    if args.only:
        keep = set(args.only.split(","))
        questions = [q for q in questions if q["id"] in keep]
    conds = [c.strip() for c in args.conditions.split(",")]
    results = {} if args.fresh or not RESULTS_JSON.exists() else json.loads(RESULTS_JSON.read_text()).get("results", {})
    for r in results.values():                       # drop empty judgments so they get redone
        if "judgment" in r and not r["judgment"].get("concepts"):
            r.pop("judgment", None); r.pop("metrics", None)
    pblock = profile_block_without_rules(profile)
    gen_name = f"claude -p ({args.claude_model or 'configured default'})" if args.generator == "claude" else lib.MODEL_GEN

    def save():
        RESULTS_JSON.write_text(json.dumps({
            "meta": {"generator": gen_name, "judge": lib.MODEL_JUDGE, "persona": spec["persona"],
                     "run_at": lib.now()},
            "results": results}, indent=1, ensure_ascii=False))

    # 1. generation
    todo = [(q, c) for q in questions for c in conds if f"{q['id']}|{c}" not in results]
    print(f"generating {len(todo)} answers with {gen_name} ({args.workers} parallel) ...", flush=True)
    t0 = time.time()

    def gen_one(q, c):
        extra = condition_text(c, profile)
        ans = gen_claude(q["q"], extra, args.claude_model) if args.generator == "claude" else gen_openai(q["q"], extra)
        return q, c, ans

    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = [ex.submit(gen_one, q, c) for q, c in todo]
        for f in as_completed(futs):
            try:
                q, c, ans = f.result()
            except Exception as e:  # noqa: BLE001
                print(f"  FAILED: {e}", flush=True)
                continue
            results[f"{q['id']}|{c}"] = {"question": q["q"], "condition": c, "answer": ans}
            print(f"  {q['id']:<14} {c}  {len(ans.split()):>4} words  ({time.time()-t0:.0f}s)", flush=True)
            save()

    # 2. judging
    todo = [k for k, r in results.items() if "judgment" not in r]
    print(f"judging {len(todo)} answers with {lib.MODEL_JUDGE} ...", flush=True)

    def judge_one(k):
        r = results[k]
        return k, judge(pblock, r["question"], r["answer"])

    with ThreadPoolExecutor(max_workers=5) as ex:
        futs = [ex.submit(judge_one, k) for k in todo]
        for f in as_completed(futs):
            try:
                k, j = f.result()
            except Exception as e:  # noqa: BLE001
                print(f"  FAILED: {e}", flush=True)
                continue
            results[k]["judgment"] = j
            results[k]["metrics"] = metrics(results[k]["answer"], j)
            m = results[k]["metrics"]
            print(f"  {k:<18} unexplained={m['unexplained']} new={m['new']} followups={m['followups']} words={m['words']}", flush=True)
            save()

    # 3. report
    meta = json.loads(RESULTS_JSON.read_text())["meta"]
    RESULTS_MD.write_text(write_report(results, questions, meta))
    print(f"\nwrote {RESULTS_MD.relative_to(ROOT)}")
    print(RESULTS_MD.read_text().split("## Per question")[0])


if __name__ == "__main__":
    main()
